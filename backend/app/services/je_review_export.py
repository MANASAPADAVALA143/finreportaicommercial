"""PDF and Excel exports for the Internal Audit JE review queue."""

from __future__ import annotations

from datetime import datetime
from io import BytesIO
from typing import Any
from xml.sax.saxutils import escape

SEVERITIES = ("Critical", "High", "Medium")
STATUSES = ("Open", "Under Review", "Cleared")
FOOTER = "Generated by FinReportAI Internal Audit Module"

_SEVERITY_FILL = {"Critical": "FECACA", "High": "FED7AA", "Medium": "FEF08A"}


def summarize(rows: list[dict[str, Any]]) -> dict[str, Any]:
    by_severity = {s: 0 for s in SEVERITIES}
    by_status = {s: 0 for s in STATUSES}
    for r in rows:
        if r.get("severity") in by_severity:
            by_severity[r["severity"]] += 1
        if r.get("status") in by_status:
            by_status[r["status"]] += 1
    return {"total": len(rows), "by_severity": by_severity, "by_status": by_status}


def _period_text(meta: dict[str, Any]) -> str:
    start, end = meta.get("period_start"), meta.get("period_end")
    if start and end:
        return f"{start} to {end}"
    if start:
        return f"From {start}"
    if end:
        return f"Up to {end}"
    return "All periods"


def build_xlsx(rows: list[dict[str, Any]], meta: dict[str, Any]) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill

    wb = Workbook()
    summary_ws = wb.active
    summary_ws.title = "Summary"
    stats = summarize(rows)
    summary_rows = [
        ("Company", meta.get("company_name") or ""),
        ("Period", _period_text(meta)),
        ("Generated", meta["generated_at"]),
        ("Prepared by", meta.get("prepared_by") or ""),
        ("", ""),
        ("Total flagged entries", stats["total"]),
        *[(f"{s} risk", n) for s, n in stats["by_severity"].items()],
        ("", ""),
        *[(f"Status: {s}", n) for s, n in stats["by_status"].items()],
    ]
    for label, value in summary_rows:
        summary_ws.append([label, value])
    for cell in summary_ws["A"]:
        cell.font = Font(bold=True)
    summary_ws.column_dimensions["A"].width = 26
    summary_ws.column_dimensions["B"].width = 48

    ws = wb.create_sheet("JE Review")
    headers = [
        ("JE ID", 16), ("Posting date", 13), ("Account", 14), ("Account name", 28),
        ("Amount", 16), ("Risk score", 11), ("Severity", 11), ("Explanation", 60),
        ("AI observation", 60), ("Status", 14), ("Auditor comment", 40), ("Reviewed by", 24),
    ]
    ws.append([h for h, _ in headers])
    header_fill = PatternFill("solid", fgColor="1E3A8A")
    for idx, (_, width) in enumerate(headers, start=1):
        cell = ws.cell(row=1, column=idx)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = header_fill
        ws.column_dimensions[cell.column_letter].width = width

    for r in rows:
        ws.append([
            r.get("journal_id"), r.get("posting_date"), r.get("account"), r.get("account_name"),
            r.get("amount"), r.get("risk_score"), r.get("severity"), r.get("explanation"),
            r.get("ai_observation"), r.get("status"), r.get("auditor_comment"), r.get("reviewed_by"),
        ])
        row_idx = ws.max_row
        ws.cell(row=row_idx, column=5).number_format = "#,##0.00"
        fill = _SEVERITY_FILL.get(r.get("severity") or "")
        if fill:
            ws.cell(row=row_idx, column=7).fill = PatternFill("solid", fgColor=fill)
        for col in (8, 9, 11):
            ws.cell(row=row_idx, column=col).alignment = Alignment(wrap_text=True, vertical="top")

    ws.freeze_panes = "A2"
    ws.auto_filter.ref = ws.dimensions

    buf = BytesIO()
    wb.save(buf)
    return buf.getvalue()


def build_pdf(rows: list[dict[str, Any]], meta: dict[str, Any]) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    styles = getSampleStyleSheet()
    body = styles["BodyText"]
    small = styles["BodyText"].clone("small", fontSize=8, leading=10)

    def p(text: Any, style=body) -> Paragraph:
        return Paragraph(escape(str(text if text is not None else "")), style)

    def footer(canvas, doc) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.grey)
        canvas.drawString(15 * mm, 10 * mm, FOOTER)
        canvas.drawRightString(A4[0] - 15 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    stats = summarize(rows)
    story: list[Any] = [
        Paragraph("Journal Entry Review — Internal Audit Report", styles["Title"]),
        p(f"Company: {meta.get('company_name') or '—'}"),
        p(f"Period: {_period_text(meta)}"),
        p(f"Generated: {meta['generated_at']}"),
        p(f"Prepared by: {meta.get('prepared_by') or '—'}"),
        Spacer(1, 6 * mm),
        Paragraph("Summary", styles["Heading2"]),
    ]
    summary_data = [["Total flagged", *SEVERITIES, *STATUSES]]
    summary_data.append([
        stats["total"],
        *[stats["by_severity"][s] for s in SEVERITIES],
        *[stats["by_status"][s] for s in STATUSES],
    ])
    summary_table = Table(summary_data, hAlign="LEFT")
    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E3A8A")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
        ("ALIGN", (0, 1), (-1, -1), "CENTER"),
    ]))
    story += [summary_table, Spacer(1, 6 * mm), Paragraph("Flagged journal entries", styles["Heading2"])]

    if not rows:
        story.append(p("No flagged journal entries for the selected period."))

    for r in rows:
        amount = r.get("amount")
        amount_text = f"{amount:,.2f}" if isinstance(amount, (int, float)) else ""
        account = r.get("account") or ""
        if r.get("account_name"):
            account = f"{account} – {r['account_name']}"
        details = [
            [p(f"JE {r.get('journal_id')}", styles["Heading4"]),
             p(f"{r.get('severity')} · score {float(r.get('risk_score') or 0):.0f} · {r.get('status')}", small)],
            [p("Account", small), p(account, small)],
            [p("Posting date / amount", small), p(f"{r.get('posting_date') or '—'} · {amount_text}", small)],
            [p("Explanation", small), p(r.get("explanation") or "—", small)],
            [p("AI observation", small), p(r.get("ai_observation") or "—", small)],
            [p("Auditor comment", small), p(r.get("auditor_comment") or "—", small)],
        ]
        t = Table(details, colWidths=[40 * mm, 135 * mm])
        t.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
            ("LINEBELOW", (0, 0), (-1, 0), 0.25, colors.grey),
        ]))
        story += [KeepTogether(t), Spacer(1, 4 * mm)]

    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=15 * mm, bottomMargin=18 * mm,
        title="JE Review — Internal Audit Report",
    )
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


def export_meta(company_name: str | None, period_start: str | None, period_end: str | None, prepared_by: str | None) -> dict[str, Any]:
    return {
        "company_name": company_name,
        "period_start": period_start,
        "period_end": period_end,
        "prepared_by": prepared_by,
        "generated_at": datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC"),
    }
